#include <iostream>
using namespace std;

int main() {
    int age = 15;
    long long population = 1400000000LL;
    double pi = 3.14159;
    char grade = 'A';
    bool isPassed = true;
    string name = "Aditi";

    cout << "int      : " << age << endl;
    cout << "long long: " << population << endl;
    cout << "double   : " << pi << endl;
    cout << "char     : " << grade << endl;
    cout << "bool     : " << isPassed << endl;
    cout << "string   : " << name << endl;
    return 0;
}
